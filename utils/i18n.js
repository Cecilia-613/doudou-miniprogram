let current = 'cn'

function setLang (lang) {
  current = dict[lang] ? lang : 'cn'
  return current
}

function getLang () {
  return current
}

/** t('suspiciousWords', {n: 3}) */
function t (key, params) {
  let s = (dict[current] && dict[current][key]) || (dict.cn[key]) || key
  if (params) {
    Object.keys(params).forEach(k => {
      s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), params[k])
    })
  }
  return s
}

