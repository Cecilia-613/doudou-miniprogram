/** 判定 */
function matchRule (text) {
  const clean = String(text || '').replace(/\s+/g, '')
  let best = null
  let bestScore = 0
  RULES.forEach(rule => {
    let score = 0
    rule.groups.forEach(g => {
      if (g.some(k => k && clean.indexOf(k) >= 0)) score++
    })
    if (score > bestScore) {
      bestScore = score
      best = rule
    }
  })
  if (!best) return null
  const need = best.minScore || 2
  if (bestScore < need) return null
  return { rule: best, score: bestScore }
}

